    public function actionVirtualReception()
    {
        $model = new Virtual();
        if ($model->load(Yii::$app->request->post())) {
            $model->file = UploadedFile::getInstance($model, 'file');
            if ($model->file) {
                $model->file->saveAs('uploads/virtual/' . $model->file->baseName . '.' . $model->file->extension);
            }
            $model->address = Yii::$app->request->post('manzil');
            $model->fog = Yii::$app->request->post('tuman');
            $model->province = Yii::$app->request->post('viloyat');
            $model->gender = Yii::$app->request->post('gender');
            $model->faculty_id = Yii::$app->request->post('fakultet');
            $model->status = 0;
            if ($model->save()) {
                Yii::$app->session->setFlash('success', 'Arizangiz qabul qilindi');
                return $this->redirect(['site/index']);
            } else {
                Yii::$app->session->setFlash('error', 'xatolik yuz berdi');
            }
            return $this->redirect(Yii::$app->request->referrer);
        }
        return $this->render('virtual-reception', ['model' => $model]);
    }

