    public function actionSearch()
    {
        $this->enableCsrfValidation = false;
        $search = Yii::$app->request->get('search');
        $news = Post::find()->where(['status' => 1])->andwhere(['like', 'title_uz', $search])->orWhere(['like', 'title_ru', $search])->orWhere(['like', 'title_en', $search]);
        $provider = new ActiveDataProvider([
            'query' => $news,
            'pagination' => [
                'pageSize' => 3,
            ],
        ]);
        $result2 = Page::find()->where(['status' => 1])->andwhere(['like', 'title_uz', $search])->orWhere(['like', 'title_ru', $search])->orWhere(['like', 'title_en', $search])->all();
        return $this->render("search", ['provider' => $provider, 'search2' => $result2]);
    }

