    /**
     * Displays homepage.
     *
     * @return mixed
     */
    public function actionIndex()
    {
        $news = Post::find()->where(['status' => 1])->orderBy('date DESC')->limit(3)->all();
        $images = Img::find()->where(['status' => 1])->orderBy('id DESC')->limit(3)->asArray()->all();
