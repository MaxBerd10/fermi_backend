            $menus = Menu::find()->where(['id' => $menu_id])->one();
            $page = Page::find()->where(['slug' => $id])->asArray()->one();
            $leader_category = Leadercategory::find()->andWhere(['slug' => $id])->one();
            if (isset($leader_category)) {
                $leaders = Leader::find()->andWhere(['category_id' => $leader_category->id])->all();
            }
            return $this->render('page', ['page' => $page, 'menus' => $menus,'leaders'=>$leaders]);
        } else {
            throw new NotFoundHttpException('The requested page does not exist.');
        }

    }

